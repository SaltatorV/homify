export class ColorSaturation {
  redSaturation: number
  greenSaturation: number
  blueSaturation: number

  constructor(redSaturation: number, greenSaturation: number, blueSaturation: number) {
    this.redSaturation = redSaturation;
    this.greenSaturation = greenSaturation;
    this.blueSaturation = blueSaturation;
  }

}
